import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader","--use-fake-device-for-media-stream","--use-fake-ui-for-media-stream"] });
const p = await b.newPage(); await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
const errs = []; p.on("pageerror", e => errs.push(String(e))); p.on("console", m => { if (m.type()==="error") errs.push(m.text()); });
const s = ms => new Promise(r => setTimeout(r, ms));
const click = (re) => p.evaluate((x) => { const r = new RegExp(x,"i"); const el=[...document.querySelectorAll("button,label")].find(b=>r.test(b.textContent.trim())||r.test(b.getAttribute("aria-label")||"")); el?.click(); return !!el; }, re);
await p.evaluateOnNewDocument(() => localStorage.setItem("pixi:onboarded","1"));
await p.goto("http://localhost:3111", { waitUntil: "domcontentloaded" }); await s(6000);
await click("^Take photo$"); await s(5000);
await click("^Studio$"); await s(3500);
await click("^Edit "); await s(2500); await p.screenshot({ path: "/tmp/s-build.png" });
await click("^Share…$"); await s(2500); await p.screenshot({ path: "/tmp/s-share.png" });
await click("^Camera$"); await s(2000);
await click("^Roll$"); await s(2000); await p.screenshot({ path: "/tmp/s-roll.png" });
await click("^Camera$"); await s(1500);
await p.evaluate(() => document.querySelector('[aria-label="Looks, film and effects"]').click()); await s(1200);
await p.evaluate(() => [...document.querySelectorAll("button")].find(b=>b.textContent.trim()==="Cameras")?.click()); await s(2500);
await p.screenshot({ path: "/tmp/s-shelf.png" });
console.log("errors:", JSON.stringify(errs));
await b.close();
